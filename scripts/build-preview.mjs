/**
 * Builds a standalone, double-clickable HTML preview of the site.
 *
 * Run: npm run preview
 * Output: ../Urban Reach Website Preview/index.html  (next to the project)
 *
 * Why this is a separate script rather than `next build`:
 *
 *  - A static export cannot contain the /api/contact route handler, which needs
 *    a running server. So this builds from a COPY of the project with that
 *    route removed, leaving the real source tree untouched.
 *  - `output: 'export'` and `images.unoptimized` are injected into the copy's
 *    config for the same reason.
 *  - The folder ships a tiny zero-dependency static server and a macOS
 *    double-click launcher. It cannot simply be opened via file://: browsers
 *    treat a file:// page as an opaque origin, so web fonts and ES modules are
 *    blocked by CORS, React never hydrates, and every scroll-revealed section
 *    stays invisible.
 *
 * The preview is for LOOKING at the site. The contact form is inert in it —
 * there is no mail server to receive a submission. Use `npm run dev` to
 * exercise the form.
 */

import { chmod, cp, mkdir, readdir, rm, symlink, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const WORK = join(ROOT, ".preview-build");
const OUT = join(ROOT, "..", "Urban Reach Website Preview");

async function main() {
  console.log("Preparing an isolated copy of the project…");
  await rm(WORK, { recursive: true, force: true });
  await mkdir(WORK, { recursive: true });

  // Copy source and config, but not build output or dependencies.
  for (const entry of ["src", "public", "package.json", "tsconfig.json", "postcss.config.mjs", "next-env.d.ts"]) {
    if (existsSync(join(ROOT, entry))) {
      await cp(join(ROOT, entry), join(WORK, entry), { recursive: true });
    }
  }
  // Symlink node_modules rather than copying it. Copying works but leaves tens
  // of thousands of files that the cleanup step then fails to remove
  // (ENOTEMPTY, from nested symlinks in dependency bin folders).
  await symlink(join(ROOT, "node_modules"), join(WORK, "node_modules"), "dir");

  // Route handlers cannot be statically exported without force-static, and
  // none of these mean anything when browsing from the filesystem:
  //   api/           — needs a live server to receive a submission
  //   opengraph-image — needs the runtime image pipeline; social previews are
  //                     not visible from file:// regardless
  //   sitemap/robots  — only meaningful to crawlers hitting a real domain
  await rm(join(WORK, "src", "app", "api"), { recursive: true, force: true });
  await rm(join(WORK, "src", "app", "opengraph-image.tsx"), { force: true });
  await rm(join(WORK, "src", "app", "sitemap.ts"), { force: true });
  await rm(join(WORK, "src", "app", "robots.ts"), { force: true });

  await writeFile(
    join(WORK, "next.config.ts"),
    `import type { NextConfig } from "next";

// Generated by scripts/build-preview.mjs — not the project's real config.
const nextConfig: NextConfig = {
  output: "export",
  images: { unoptimized: true },
  trailingSlash: false,
};

export default nextConfig;
`,
  );

  console.log("Building the static export (this takes a minute)…");
  execFileSync("npx", ["next", "build"], {
    cwd: WORK,
    stdio: "inherit",
    env: { ...process.env, NEXT_PUBLIC_SITE_URL: "https://urbanreachtx.com" },
  });

  console.log("Assembling the preview folder…");
  await rm(OUT, { recursive: true, force: true });
  await cp(join(WORK, "out"), OUT, { recursive: true });
  await tidy(OUT);

  await rm(WORK, { recursive: true, force: true });

  console.log(`\nPreview ready:\n  ${OUT}\n`);
  console.log('Double-click "Open Urban Reach Preview.command" inside that folder.');
  console.log("Note: the contact form cannot submit in the preview — there is no");
  console.log("mail server behind it. Run `npm run dev` to exercise the form.\n");
}

/** Collect every file under a directory, recursively. */
async function allFiles(dir) {
  const found = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) found.push(...(await allFiles(full)));
    else found.push(full);
  }
  return found;
}

/**
 * Tidy the export for a non-technical reviewer.
 *
 * Deliberately does NOT rewrite any URLs. An earlier version rewrote absolute
 * paths to relative ones so the folder could be browsed via file://, but that
 * is a dead end: file:// pages are an opaque origin, so fonts and ES modules
 * are blocked by CORS and React never hydrates — every scroll-revealed section
 * stays invisible. The launcher serves over http instead, where Next's own
 * absolute paths work untouched.
 */
async function tidy(outDir) {
  // Next also emits React Server Component payloads (.txt) and per-route
  // directories that only contain them. They are dead weight in a
  // double-clickable preview and make the folder confusing to read, so strip
  // them, leaving just the HTML pages and their assets.
  for (const entry of await readdir(outDir, { withFileTypes: true })) {
    const full = join(outDir, entry.name);
    if (entry.isFile() && entry.name.endsWith(".txt")) {
      await rm(full, { force: true });
    } else if (entry.isDirectory()) {
      // Only remove a directory if EVERYTHING under it is an RSC payload.
      // An earlier version removed any directory containing no .html and
      // whitelisted `_next` and `brand` by name, which silently deleted
      // public/hero — the entire hero photography set — from the review copy.
      const files = await allFiles(full);
      const onlyPayloads = files.length > 0 && files.every((f) => f.endsWith(".txt"));
      if (files.length === 0 || onlyPayloads) {
        await rm(full, { recursive: true, force: true });
      }
    }
  }

  await writeLauncher(outDir);

  // A short readme inside the folder, for whoever opens it later.
  await writeFile(
    join(outDir, "READ ME FIRST.txt"),
    [
      "URBAN REACH — WEBSITE PREVIEW",
      "",
      "HOW TO OPEN IT",
      'Double-click "Open Urban Reach Preview.command".',
      "",
      "A small black Terminal window will appear and your browser will open the",
      "site. Leave that Terminal window open while you are looking around.",
      "When you are finished, close the Terminal window.",
      "",
      "The first time you double-click it, macOS may say it cannot verify the",
      "developer. If that happens: right-click the file, choose Open, then",
      'click Open again in the box that appears. You only do this once.',
      "",
      "WHY NOT JUST DOUBLE-CLICK index.html?",
      "Because browsers block web fonts and scripts when a page is opened",
      "straight off the hard drive, for security reasons. The page would load",
      "with the wrong fonts and none of the animation. The launcher above",
      "avoids that, and shows you exactly what visitors will see.",
      "",
      "EVERY PAGE IS A REAL, SEPARATE PAGE",
      "You can see them in this folder as individual files: index.html,",
      "about.html, appliances.html, process.html, contact.html and",
      "privacy-policy.html. Each one has its own web address and gets its own",
      "listing in Google. Watch the address bar as you click the menu — it",
      "changes every time. Nothing in the navigation is a button that just",
      "scrolls down the same page.",
      "",
      "WHAT DOES NOT WORK IN THIS PREVIEW",
      "The contact form will not actually send. Sending email needs a live",
      "server, and this is a copy running on your own computer. Everything",
      "else works: every page, the scrolling appliance animation, the mobile",
      "menu.",
      "",
      "This is a review copy. It is not the published website.",
    ].join("\n"),
  );
}

/**
 * A static file server plus a macOS double-click launcher.
 *
 * Opening the export via file:// does not work: Chrome and Safari treat a
 * file:// page as an opaque origin, so web fonts and ES modules are blocked by
 * CORS. The HTML renders but React never hydrates, which leaves every
 * scroll-revealed section stuck invisible. Serving over http on localhost
 * sidesteps all of that, and Node is already required to build this, so the
 * server needs no dependencies.
 */
async function writeLauncher(outDir) {
  await writeFile(
    join(outDir, "serve.mjs"),
    `import { createServer } from "node:http";
import { readFile, stat } from "node:fs/promises";
import { join, extname, dirname, normalize } from "node:path";
import { fileURLToPath } from "node:url";
import { execFile } from "node:child_process";

const ROOT = dirname(fileURLToPath(import.meta.url));

const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".mjs": "text/javascript; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".webp": "image/webp",
  ".ico": "image/x-icon",
  ".woff2": "font/woff2",
  ".woff": "font/woff",
  ".txt": "text/plain; charset=utf-8",
};

async function resolve(urlPath) {
  // normalize + strip leading separators keeps requests inside ROOT.
  const clean = normalize(decodeURIComponent(urlPath.split("?")[0])).replace(/^([/\\\\.]+)/, "");
  const candidates = clean === "" ? ["index.html"] : [clean, clean + ".html", join(clean, "index.html")];
  for (const c of candidates) {
    const full = join(ROOT, c);
    if (!full.startsWith(ROOT)) continue;
    try {
      if ((await stat(full)).isFile()) return full;
    } catch {}
  }
  return null;
}

const server = createServer(async (req, res) => {
  const file = await resolve(req.url ?? "/");
  if (!file) {
    const notFound = await resolve("/404.html");
    if (notFound) {
      res.writeHead(404, { "content-type": TYPES[".html"] });
      res.end(await readFile(notFound));
    } else {
      res.writeHead(404).end("Not found");
    }
    return;
  }
  res.writeHead(200, {
    "content-type": TYPES[extname(file).toLowerCase()] ?? "application/octet-stream",
    "cache-control": "no-cache",
  });
  res.end(await readFile(file));
});

server.listen(0, "127.0.0.1", () => {
  const { port } = server.address();
  const url = \`http://localhost:\${port}/\`;
  console.log("");
  console.log("  Urban Reach — website preview");
  console.log("  " + url);
  console.log("");
  console.log("  Your browser should open automatically.");
  console.log("  Close this window when you are finished looking around.");
  console.log("");
  execFile("open", [url]);
});
`,
  );

  const launcher = join(outDir, "Open Urban Reach Preview.command");
  await writeFile(
    launcher,
    `#!/bin/bash
# Double-click this file to view the Urban Reach website preview.
cd "$(dirname "$0")" || exit 1

if ! command -v node >/dev/null 2>&1; then
  echo ""
  echo "  Node.js is not installed on this Mac, so the preview cannot start."
  echo "  Install it from https://nodejs.org (choose the LTS button),"
  echo "  then double-click this file again."
  echo ""
  read -r -p "  Press Return to close this window. " _
  exit 1
fi

node serve.mjs
`,
  );
  await chmod(launcher, 0o755);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
